CREATE SCHEMA IF NOT EXISTS dwh;

-- Eliminación de tablas previas respetando dependencias
DROP TABLE IF EXISTS dwh.FACT_Accidentes CASCADE;
DROP TABLE IF EXISTS dwh.DIM_Tiempo CASCADE;
DROP TABLE IF EXISTS dwh.DIM_Ubicacion CASCADE;
DROP TABLE IF EXISTS dwh.DIM_Vehiculo CASCADE;
DROP TABLE IF EXISTS dwh.DIM_Contexto_Siniestro CASCADE;

-- -----------------------------------------------------------------------------
-- 1. DIM_Tiempo
-- -----------------------------------------------------------------------------
CREATE TABLE dwh.DIM_Tiempo (
    ID_Tiempo       INT PRIMARY KEY, -- Formato entero YYYYMMDD
    Fecha           DATE NOT NULL,
    Anio            INT NOT NULL,
    Mes             INT NOT NULL CHECK (Mes BETWEEN 1 AND 12),
    Dia             INT NOT NULL CHECK (Dia BETWEEN 1 AND 31),
    Dia_Semana      VARCHAR(10) NOT NULL,
    Festividad      VARCHAR(50) NOT NULL
);

COMMENT ON TABLE dwh.DIM_Tiempo IS 'Dimensión de tiempo con grano diario para análisis cronológico e interanual.';

-- -----------------------------------------------------------------------------
-- 2. DIM_Ubicacion
-- -----------------------------------------------------------------------------
CREATE TABLE dwh.DIM_Ubicacion (
    ID_Ubicacion    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Distrito_Area   VARCHAR(100) NOT NULL,
    Area_Urbana     VARCHAR(50) NOT NULL,
    Latitud         DECIMAL(10,6),
    Longitud        DECIMAL(10,6),
    CONSTRAINT uq_dim_ubicacion UNIQUE (Distrito_Area, Area_Urbana, Latitud, Longitud)
);

COMMENT ON TABLE dwh.DIM_Ubicacion IS 'Dimensión geográfica depurada con coordenadas normalizadas.';

-- -----------------------------------------------------------------------------
-- 3. DIM_Vehiculo
-- -----------------------------------------------------------------------------
CREATE TABLE dwh.DIM_Vehiculo (
    ID_Vehiculo         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Categoria_Vehiculo  VARCHAR(50) NOT NULL,
    Tipo_Vehiculo       VARCHAR(100) NOT NULL,
    CONSTRAINT uq_dim_vehiculo UNIQUE (Categoria_Vehiculo, Tipo_Vehiculo)
);

COMMENT ON TABLE dwh.DIM_Vehiculo IS 'Dimensión de transporte con agrupación por macro-categoría de flota.';

-- -----------------------------------------------------------------------------
-- 4. DIM_Contexto_Siniestro (Junk Dimension)
-- -----------------------------------------------------------------------------
CREATE TABLE dwh.DIM_Contexto_Siniestro (
    ID_Contexto_Siniestro   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Condicion_Luz           VARCHAR(80) NOT NULL,
    Condicion_Clima         VARCHAR(80) NOT NULL,
    Condicion_Superficie    VARCHAR(80) NOT NULL,
    Tipo_Calzada            VARCHAR(80) NOT NULL,
    Severidad               VARCHAR(50) NOT NULL,
    CONSTRAINT uq_dim_contexto UNIQUE (Condicion_Luz, Condicion_Clima, Condicion_Superficie, Tipo_Calzada, Severidad)
);

COMMENT ON TABLE dwh.DIM_Contexto_Siniestro IS 'Junk Dimension que combina atributos circunstanciales del siniestro.';

-- -----------------------------------------------------------------------------
-- 5. FACT_Accidentes
-- -----------------------------------------------------------------------------
CREATE TABLE dwh.FACT_Accidentes (
    ID_Fact_Accidente        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_Tiempo                INT NOT NULL,
    ID_Ubicacion             INT NOT NULL,
    ID_Vehiculo              INT NOT NULL,
    ID_Contexto_Siniestro    INT NOT NULL,
    Cantidad_Accidentes      INT NOT NULL DEFAULT 1 CHECK (Cantidad_Accidentes = 1),
    Cantidad_Victimas        INT NOT NULL CHECK (Cantidad_Victimas >= 0),
    Cantidad_Vehiculos       INT NOT NULL CHECK (Cantidad_Vehiculos >= 1),
    
    CONSTRAINT fk_fact_tiempo FOREIGN KEY (ID_Tiempo) 
        REFERENCES dwh.DIM_Tiempo (ID_Tiempo) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_fact_ubicacion FOREIGN KEY (ID_Ubicacion) 
        REFERENCES dwh.DIM_Ubicacion (ID_Ubicacion) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_fact_vehiculo FOREIGN KEY (ID_Vehiculo) 
        REFERENCES dwh.DIM_Vehiculo (ID_Vehiculo) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_fact_contexto FOREIGN KEY (ID_Contexto_Siniestro) 
        REFERENCES dwh.DIM_Contexto_Siniestro (ID_Contexto_Siniestro) ON UPDATE RESTRICT ON DELETE RESTRICT
);

COMMENT ON TABLE dwh.FACT_Accidentes IS 'Tabla de hechos a grano de accidente individual con medidas aditivas.';

-- -----------------------------------------------------------------------------
-- Índices para optimización de consultas analíticas (OLAP / BI)
-- -----------------------------------------------------------------------------
CREATE INDEX idx_fact_tiempo ON dwh.FACT_Accidentes(ID_Tiempo);
CREATE INDEX idx_fact_ubicacion ON dwh.FACT_Accidentes(ID_Ubicacion);
CREATE INDEX idx_fact_vehiculo ON dwh.FACT_Accidentes(ID_Vehiculo);
CREATE INDEX idx_fact_contexto ON dwh.FACT_Accidentes(ID_Contexto_Siniestro);

